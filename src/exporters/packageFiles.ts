export function generatePackageXml(project: Project, target: TargetConfig): string {
  return `<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>${escapeXml(project.name)}</name>
  <version>0.1.0</version>
  <description>ROS 2 robot description and ${target.gazeboName} simulation package generated by RoboForge.</description>
  <maintainer email="robotics@example.com">RoboForge User</maintainer>
  <license>Apache-2.0</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <exec_depend>xacro</exec_depend>
  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <exec_depend>${target.simLaunchPackage}</exec_depend>
  <exec_depend>${target.bridgePackage}</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
`;
}

export function generateCMakeLists(project: Project): string {
  return `cmake_minimum_required(VERSION 3.8)
project(${project.name})

if(CMAKE_COMPILER_IS_GNUCXX OR CMAKE_CXX_COMPILER_ID MATCHES "Clang")
  add_compile_options(-Wall -Wextra -Wpedantic)
endif()

find_package(ament_cmake REQUIRED)

install(
  DIRECTORY urdf sdf worlds launch config meshes scripts
  DESTINATION share/\${PROJECT_NAME}
)

ament_package()
`;
}

export function generateRvizConfig(project: Project): string {
  const rootLink =
    project.robot.links.find((l) => l.id === project.robot.rootLinkId)?.name ?? 'base_link';
  const lidar = project.robot.sensors.find((s) => s.kind === 'lidar2d');

  const scanBlock = lidar
    ? `    - Class: rviz_default_plugins/LaserScan
      Name: LaserScan
      Enabled: true
      Topic:
        Value: ${lidar.topic}
        Reliability Policy: Best Effort
      Size (m): 0.04
      Color: 59; 130; 246`
    : '';

  return `Panels:
  - Class: rviz_common/Displays
    Name: Displays
  - Class: rviz_common/Views
    Name: Views
Visualization Manager:
  Class: ""
  Displays:
    - Class: rviz_default_plugins/Grid
      Name: Grid
      Enabled: true
      Cell Size: 0.5
      Plane Cell Count: 20
      Color: 75; 85; 99
    - Class: rviz_default_plugins/RobotModel
      Name: RobotModel
      Enabled: true
      Description Topic:
        Value: /robot_description
    - Class: rviz_default_plugins/TF
      Name: TF
      Enabled: true
      Show Axes: true
      Show Names: true
${scanBlock ? scanBlock + '\n' : ''}  Global Options:
    Background Color: 20; 24; 32
    Fixed Frame: ${rootLink}
  Views:
    Current:
      Class: rviz_default_plugins/Orbit
      Distance: 2.2
      Pitch: 0.55
      Yaw: 0.78
`;
}

export function generateValidateMd(project: Project, target: TargetConfig): string {
  const pkg = project.name;
  const robot = project.robot.name;
  const world = project.world.name;

  return `# Validation Commands (${target.label})

## 1. Expand Xacro and run \`check_urdf\`

\`\`\`bash
xacro install/${pkg}/share/${pkg}/urdf/${robot}.urdf.xacro -o /tmp/${robot}.urdf
check_urdf /tmp/${robot}.urdf
\`\`\`

## 2. Validate SDF Robot & World with Gazebo

\`\`\`bash
${target.gzCommand} sdf --check install/${pkg}/share/${pkg}/sdf/${robot}.sdf
${target.gzCommand} sdf --check install/${pkg}/share/${pkg}/worlds/${world}.sdf
\`\`\`
`;
}

export function generatePackageReadme(project: Project, target: TargetConfig): string {
  const pkg = project.name;

  return `# ${pkg}

Generated by **RoboForge** for **${target.label}**.

## Dependencies

\`\`\`bash
sudo apt-get update
sudo apt-get install -y ${target.aptInstallPackages.join(' ')}
\`\`\`

## Build

\`\`\`bash
mkdir -p ~/ros2_ws/src
cp -r ${pkg} ~/ros2_ws/src/
cd ~/ros2_ws
colcon build --packages-select ${pkg}
source install/setup.bash
\`\`\`

## Launch in ${target.gazeboName}

\`\`\`bash
ros2 launch ${pkg} sim.launch.py
\`\`\`

Drive with keyboard or \`/cmd_vel\`:

\`\`\`bash
ros2 topic pub /cmd_vel geometry_msgs/msg/Twist "{linear: {x: 0.3}, angular: {z: 0.2}}"
\`\`\`

## Preview in RViz2

\`\`\`bash
ros2 launch ${pkg} display.launch.py
\`\`\`

## Validation

See \`scripts/validate.md\` for \`check_urdf\` and \`${target.gzCommand} sdf --check\` commands.
`;
}
